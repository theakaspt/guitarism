/** 팁 안에 나온 용어만 골라낸다 (최대 2개 — 설명이 팁보다 길어지면 안 된다) */
export function termsIn(tip) {
  if (!tip) return [];
  const hay = `${tip.text} ${tip.more}`;
  return Object.keys(TERMS).filter((t) => hay.includes(t)).slice(0, 2);
}

/**
 * 지금 화면·상태에 맞는 팁 하나를 고른다.
 * @param where   화면 키
 * @param ctx     현재 선택 상태
 * @param skip    이미 닫은 팁 id 집합 (세션 동안만 유지 — 저장하지 않는다)
 * @returns 팁 하나 또는 null
 */
export function pickTip(where, ctx, skip) {
  for (const tip of TIPS) {
    if (tip.where !== where) continue;
    if (skip && skip.has(tip.id)) continue;
    let match = false;
    try { match = !!tip.cond(ctx || {}); } catch (e) { match = false; }
    if (match) return tip;
  }
  return null;
}
